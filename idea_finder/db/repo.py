"""All database writes and reads for idea-finder go through this module.

Stages never touch SQL themselves: they call these functions, which own the
idempotency guarantees (canonical-URL dedup, ON CONFLICT clauses, single
active LLM provider). Connections are injectable for tests; production code
passes a connection opened via ``bootstrap_pgserver.ensure_pgserver()``.

UUIDv7 row IDs are generated by the database (``uuid_generate_v7()``,
migration 001), so insert functions never specify ``id``.

Usage (smoke test)::

    python -m idea_finder.db.repo [data_dir]
"""

